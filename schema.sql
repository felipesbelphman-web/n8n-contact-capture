-- Run in a dedicated Supabase project using SQL Editor.
-- Creates the table only if it does not exist; does not migrate an existing table.
CREATE TABLE IF NOT EXISTS public.contacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  name text,
  service text,
  message text
);
ALTER TABLE public.contacts ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT ON TABLE public.contacts TO service_role;
GRANT USAGE ON SEQUENCE public.contacts_id_seq TO service_role;
